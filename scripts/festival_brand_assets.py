#!/usr/bin/env python3
"""Publish version 07 seal assets and derive a flat stroke from its actual brush edge.

Requires ImageMagick and Potrace. Run festival_trace_seal.py first only when changing the master.
No runtime random texture, SVG filters, raster data in vectors, or font dependencies.
"""
from pathlib import Path
import copy
import json
import math
import subprocess
import tempfile
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
MASTER = ROOT / 'design/handstandfest-selo-07/hf-brush.svg'
PUB = ROOT / 'public/festival/brand'
NS = '{http://www.w3.org/2000/svg}'
ET.register_namespace('', NS[1:-1])
PUB.mkdir(parents=True, exist_ok=True)
tree = ET.parse(MASTER)
brush = tree.getroot().find(f"{NS}g[@id='brush']")
hf = tree.getroot().find(f"{NS}path[@id='hf']")

def run(*args):
    subprocess.run(args, check=True)

for variant, ink, letters in [('green', '#0f3d33', '#ffd23f'), ('yellow', '#ffd23f', '#0f3d33')]:
    root = copy.deepcopy(tree.getroot())
    root.find(f"{NS}g[@id='brush']").set('fill', ink)
    root.find(f"{NS}path[@id='hf']").set('fill', letters)
    root.find(NS + 'desc').text = 'Upright HF on a brush circle with transparent dry-paint gaps.'
    svg = PUB / f'hf-{variant}-v7.svg'
    ET.ElementTree(root).write(svg, encoding='unicode', xml_declaration=True)
    for size in [96, 192, 384, 768]:
        png = PUB / f'hf-{variant}-v7-{size}.png'
        run('magick', '-background', 'none', str(svg), '-resize', f'{size}x{size}', str(png))
        run('magick', str(png), '-define', 'webp:lossless=true', str(png.with_suffix('.webp')))

with tempfile.TemporaryDirectory() as scratch:
    scratch = Path(scratch)
    # Render only the brush silhouette, then sample its perimeter into a horizontal mark.
    source = ET.Element(NS + 'svg', {'viewBox': '0 0 1040 1040', 'width': '1040', 'height': '1040'})
    solid = copy.deepcopy(brush)
    solid.set('fill', '#000')
    source.append(solid)
    ET.ElementTree(source).write(scratch / 'brush.svg')
    run('magick', '-background', 'white', str(scratch / 'brush.svg'), '-alpha', 'remove',
        '-colorspace', 'Gray', '-depth', '8', f'gray:{scratch / "brush.gray"}')
    pixels = (scratch / 'brush.gray').read_bytes()
    assert len(pixels) == 1040 * 1040

    def sample(angle, radius):
        x = round(520 + radius * math.cos(angle))
        y = round(530 + radius * math.sin(angle))
        return 0 <= x < 1040 and 0 <= y < 1040 and pixels[y * 1040 + x] < 128

    width, height = 1200, 300
    data = bytearray()
    for y in range(height):
        for x in range(width):
            u = x / (width - 1)
            # Unwrap the top/bottom arcs; keep a solid center for readable type.
            top = sample(-math.pi + u * math.pi, 525 - y * 1.7) if y < 75 else True
            bottom = sample(math.pi - u * math.pi, 525 - (height - 1 - y) * 1.7) if y >= 225 else True
            left = sample(math.pi + (y / height - .5) * .7, 518 - x * 2.2) if x < 55 else True
            right = sample((y / height - .5) * .8, 530 - (width - 1 - x) * 1.7) if x >= width - 75 else True
            data.append(0 if top and bottom and left and right else 255)
    pgm = scratch / 'stroke.pgm'
    pgm.write_bytes(f'P5\n{width} {height}\n255\n'.encode() + data)
    run('potrace', str(pgm), '--svg', '--turdsize', '5', '--alphamax', '0.8',
        '--opttolerance', '0.2', '--output', str(scratch / 'stroke.svg'))
    stroke = ET.parse(scratch / 'stroke.svg').getroot().find(NS + 'g')
    stroke.set('transform', 'translate(0 100) scale(.0333333333 -.0333333333)')
    svg = ET.Element(NS + 'svg', {'viewBox': '0 0 400 100', 'preserveAspectRatio': 'none'})
    svg.append(stroke)
    ET.ElementTree(svg).write(PUB / 'stroke-v7.svg', encoding='unicode', xml_declaration=True)

def paths(group):
    return ' '.join(' '.join(p.get('d').split()) for p in group.findall(NS + 'path'))

values = {
    'CIRCULO': {'corpo': paths(brush), 'transform': 'translate(0 200) scale(.01923076923 -.01923076923)'},
    'HF': {'d': hf.get('d'), 'transform': 'scale(.1923076923) translate(-280 -200)'},
    'TRACO': {'corpo': paths(stroke), 'transform': stroke.get('transform')},
}
(ROOT / 'src/festival/pincel.ts').write_text(
    '// GENERATED by scripts/festival_brand_assets.py from the version 07 master. Do not edit.\n'
    '// CIRCULO/HF: 200 square. TRACO: 400 × 100. Holes are genuine transparency.\n' +
    '\n'.join(f'export const {name} = {json.dumps(value)} as const;' for name, value in values.items()) + '\n')
print('Generated shared vectors and responsive PNG/WebP assets in', PUB)
